//! Bilingual localization (English / Español) for SekhmetX.

#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Lang {
    #[default]
    En,
    Es,
}

impl Lang {
    pub fn from_code(s: &str) -> Self {
        if s.eq_ignore_ascii_case("es") || s.to_ascii_lowercase().starts_with("es") {
            Lang::Es
        } else {
            Lang::En
        }
    }
}

